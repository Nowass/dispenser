#!/usr/bin/env python3
"""Generator for test-vectors/ble_session_v1.txt (Dispenser V2 BLE session security, M1.10c.2).

Independent reference for the derivations of docs/BLE_PROTOCOL.md section 11 (PSK, prologue,
device_id_hash). Only the Python standard library is used (hmac, hashlib); RFC 5869 HKDF is
written out below and checked against the RFC's own test cases 1-3 before any vector is
emitted. It shares no code with the implementations under test (firmware: mbedTLS/TF-PSA-Crypto
on the ESP32-C3, libsodium in the host tests; Android: libsodium). A vector an implementation
fails is a contract bug to investigate, never a value to regenerate from that implementation.

Usage: python3 -I gen_ble_session_v1.py > ../ble_session_v1.txt
Deterministic output (no randomness, no time).
"""
import hashlib
import hmac
import struct
import sys

# ---- RFC 5869 HKDF-SHA256 (stdlib HMAC) --------------------------------------------------------


def hkdf_extract(salt: bytes, ikm: bytes) -> bytes:
    return hmac.new(salt if salt else bytes(32), ikm, hashlib.sha256).digest()


def hkdf_expand(prk: bytes, info: bytes, length: int) -> bytes:
    out, t, i = b"", b"", 1
    while len(out) < length:
        t = hmac.new(prk, t + info + bytes([i]), hashlib.sha256).digest()
        out += t
        i += 1
    return out[:length]


def hkdf(salt: bytes, ikm: bytes, info: bytes, length: int) -> bytes:
    return hkdf_expand(hkdf_extract(salt, ikm), info, length)


def self_check() -> None:
    """RFC 5869 Appendix A, test cases 1-3 (SHA-256)."""
    h = bytes.fromhex
    cases = [
        (h("0b" * 22), h("000102030405060708090a0b0c"), h("f0f1f2f3f4f5f6f7f8f9"), 42,
         "3cb25f25faacd57a90434f64d0362f2a2d2d0a90cf1a5a4c5db02d56ecc4c5bf34007208d5b887185865"),
        (bytes(range(0x00, 0x50)), bytes(range(0x60, 0xB0)), bytes(range(0xB0, 0x100)), 82,
         "b11e398dc80327a1c8e7f78c596a49344f012eda2d4efad8a050cc4c19afa97c59045a99cac7827271cb41c65e590e09da3275600c2f09b8367793a9aca3db71cc30c58179ec3e87c14c01d5c1f3434f1d87"),
        (h("0b" * 22), b"", b"", 42,
         "8da4e775a563c18f715f802a063c5a31b8a11f5c5ee1879ec3454e5f3c738d2d9d201395faa4b61a96c8"),
    ]
    for ikm, salt, info, n, okm in cases:
        if hkdf(salt, ikm, info, n).hex() != okm:
            sys.exit("RFC 5869 self-check failed: the reference HKDF is wrong, no vectors written")


# ---- Derivations (docs/BLE_PROTOCOL.md section 11) ----------------------------------------------

PSK_SALT = b"DSP2 psk"                  # 8 ASCII bytes, fixed protocol label
PROLOGUE_LABEL = b"DSP2 BLE v1"          # 11 ASCII bytes
ID_LABEL_CLAIMED = b"DSP2 id"            # device_id_hash of the identity public key
ID_LABEL_DEVICE = b"DSP2 dev"            # device_id_hash of the 6-byte device ID (MAC)
PURPOSES = {"session": 1, "claim": 2, "add": 3, "recovery": 4}


def psk(purpose: int, setup_code: bytes, token: bytes) -> bytes:
    assert len(setup_code) == 16 and len(token) in (0, 16)
    return hkdf(PSK_SALT, setup_code, bytes([purpose]) + token, 32)


def prologue(major: int, minor: int, purpose: int, id_hash: bytes, session_id: int) -> bytes:
    assert len(id_hash) == 8
    return PROLOGUE_LABEL + bytes([major, minor, purpose]) + id_hash + struct.pack("<I", session_id)


def id_hash_claimed(id_pub: bytes) -> bytes:
    assert len(id_pub) == 32
    return hashlib.sha256(ID_LABEL_CLAIMED + id_pub).digest()[:8]


def id_hash_device(device_id: bytes) -> bytes:
    assert len(device_id) == 6
    return hashlib.sha256(ID_LABEL_DEVICE + device_id).digest()[:8]


def x(b: bytes) -> str:
    return "x:" + b.hex() if b else "-"


def det(seed: str, n: int) -> bytes:
    """Deterministic 'random-looking' test bytes (SHA-256 counter mode over a label)."""
    out, i = b"", 0
    while len(out) < n:
        out += hashlib.sha256(f"{seed}/{i}".encode()).digest()
        i += 1
    return out[:n]


def main() -> None:
    self_check()
    lines = [
        "# BLE session security v1 vectors (docs/BLE_PROTOCOL.md section 11). Generated by",
        "# tools/gen_ble_session_v1.py with the Python standard library only (RFC 5869 HKDF written out and",
        "# self-checked against RFC 5869 test cases 1-3), never by the implementations under test.",
        "# A vector one side fails is a contract bug to investigate, not a value to regenerate.",
        "#",
        "# Format: one record per line, \"<record> key=value ...\"; bytes \"x:<hex>\", \"-\" = empty.",
        "#",
        "#   psk       PSK = HKDF-SHA256(salt=\"DSP2 psk\", ikm=setup, info=purpose u8 || token, L=32).",
        "#   psk_not   a value the PSK derivation MUST NOT produce for these inputs: \"psk\" is the",
        "#             correct result (must match), \"wrong\" the result of the named mistake (must differ).",
        "#   prologue  \"DSP2 BLE v1\" || major u8 || minor u8 || purpose u8 || hash(8) || session_id u32 LE.",
        "#   idhash    device_id_hash: SHA-256(\"DSP2 id\" || id_pub)[0..8) when claimed,",
        "#             SHA-256(\"DSP2 dev\" || device_id(6))[0..8) when unclaimed or credentials damaged.",
        "",
    ]
    setups = {
        "zero": bytes(16),
        "ones": b"\xff" * 16,
        "alt": bytes([0x55, 0xAA] * 8),
        "rand": det("setup", 16),
    }
    tokens = {"zero": bytes(16), "ones": b"\xff" * 16, "rand": det("token", 16)}
    # Positive PSK vectors: every purpose x every setup code; ADD additionally x every token.
    for sname, s in setups.items():
        for pname, p in PURPOSES.items():
            if pname == "add":
                for tname, t in tokens.items():
                    lines.append(f"psk name={pname}_{sname}_token_{tname} purpose={p} setup={x(s)} "
                                 f"token={x(t)} psk={x(psk(p, s, t))}")
            else:
                lines.append(f"psk name={pname}_{sname} purpose={p} setup={x(s)} token=- "
                             f"psk={x(psk(p, s, b''))}")
    lines.append("")
    # Negative vectors: the correct PSK and the result of a specific mistake (must differ).
    s, t = setups["rand"], tokens["rand"]
    for pname in ("claim", "add"):
        p = PURPOSES[pname]
        tok = t if pname == "add" else b""
        good = psk(p, s, tok)
        info = bytes([p]) + tok
        mistakes = {
            # context moved from HKDF info into the salt (not equivalent: different PRK)
            "context_in_salt": hkdf(PSK_SALT + info, s, b"", 32),
            "salt_info_swapped": hkdf(info, s, PSK_SALT, 32),
            "empty_salt": hkdf(b"", s, info, 32),
            "wrong_purpose": psk(PURPOSES["recovery"] if p != 4 else 2, s, tok),
            "setup_bit_flip": psk(p, bytes([s[0] ^ 0x01]) + s[1:], tok),
        }
        if pname == "add":
            mistakes["token_bit_flip"] = psk(p, s, bytes([t[0] ^ 0x80]) + t[1:])
            mistakes["token_omitted"] = psk(p, s, b"")
        for mname, wrong in mistakes.items():
            assert wrong != good, mname
            lines.append(f"psk_not name={pname}_{mname} purpose={p} setup={x(s)} token={x(tok)} "
                         f"psk={x(good)} wrong={x(wrong)}")
    lines.append("")
    # Prologue vectors.
    hashes = {"zero": bytes(8), "rand": det("hash", 8)}
    for pname, p in PURPOSES.items():
        for hname, hv in hashes.items():
            for sid in (1, 0x12345678, 0xFFFFFFFF):
                lines.append(f"prologue name={pname}_{hname}_{sid:08x} major=1 minor=0 purpose={p} "
                             f"hash={x(hv)} session_id={sid} prologue={x(prologue(1, 0, p, hv, sid))}")
    lines.append("")
    # device_id_hash vectors.
    for name, pub in (("zero", bytes(32)), ("ones", b"\xff" * 32), ("rand", det("idpub", 32))):
        lines.append(f"idhash name=claimed_{name} kind=claimed input={x(pub)} hash={x(id_hash_claimed(pub))}")
    for name, mac in (("zero", bytes(6)), ("ones", b"\xff" * 6), ("rand", det("mac", 6))):
        lines.append(f"idhash name=device_{name} kind=device input={x(mac)} hash={x(id_hash_device(mac))}")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
