#!/usr/bin/env python3
"""Generator of test-vectors/qr_formats_v1.txt (M1.10e, docs/ANDROID_BLE_DESIGN.md 7.1, decision E11).

Setup label (existing format of firmware/tools/provision_dev_secrets.py) and invitation (DSP2I1).
Python standard library only (hashlib SHA-256, integer base32 conversion); no cryptographic
primitive is implemented here. All values are visibly synthetic TEST data.

    python3 -I gen_qr_formats_v1.py > ../qr_formats_v1.txt

Deterministic. As a cross-check the label encoding is compared with the provisioning tool's own
function when that file is present (it is in this repository).
"""
import hashlib
import importlib.util
import os
import struct
import sys

CROCKFORD = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"
HERE = os.path.dirname(os.path.abspath(__file__))


def b32(data, nchars):
    """MSB-first Crockford base32 of `data`, zero pad bits at the end, exactly `nchars` chars."""
    nbits = len(data) * 8
    pad = nchars * 5 - nbits
    assert 0 <= pad < 5
    n = int.from_bytes(data, "big") << pad
    return "".join(CROCKFORD[(n >> (5 * (nchars - 1 - i))) & 31] for i in range(nchars))


# ---- setup label ---------------------------------------------------------------------------------

def label_code(code):
    body = b32(code, 26)
    check = int.from_bytes(hashlib.sha256(b"DSP2 setup" + code).digest()[:2], "big") >> 6
    return body + CROCKFORD[check >> 5] + CROCKFORD[check & 31]


def label(device_id_hex, code):
    return "DSP2:" + device_id_hex + ":" + label_code(code)


# ---- invitation ----------------------------------------------------------------------------------

def invite_payload(version, device_id, pub, token, expires, created):
    body = bytes([version]) + device_id + pub + token + struct.pack("<I", expires) + struct.pack("<I", created)
    assert len(body) == 63
    return body + hashlib.sha256(b"DSP2 invite v1" + body).digest()[:16]


def invite_text(payload):
    assert len(payload) == 79
    return "DSP2I1:" + b32(payload, 127)


def id_hash(pub):
    return hashlib.sha256(b"DSP2 id" + pub).digest()[:8]


def hx(b):
    return "x:" + b.hex() if b else "-"


def cross_check():
    path = os.path.join(HERE, "..", "..", "firmware", "tools", "provision_dev_secrets.py")
    if not os.path.exists(path):
        return False
    spec = importlib.util.spec_from_file_location("pds", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    for code in (bytes(16), b"\xff" * 16, bytes(range(16)), bytes.fromhex("fd5b144a7bcff1dd4c00587c39bbd561")):
        if mod.setup_label_code(code) != label_code(code):
            sys.exit("label encoding differs from firmware/tools/provision_dev_secrets.py")
    return True


def main():
    checked = cross_check()
    out = []
    w = out.append
    w("# QR and code formats v1 (docs/ANDROID_BLE_DESIGN.md section 7.1). Generated by")
    w("# tools/gen_qr_formats_v1.py (Python standard library: hashlib SHA-256 and integer base32 only).")
    w("# Label encoding cross-checked against firmware/tools/provision_dev_secrets.py: %s." % ("yes" if checked else "not available"))
    w("# All values are visibly synthetic TEST data, never real secrets.")
    w("#")
    w("# Crockford alphabet 0123456789ABCDEFGHJKMNPQRSTVWXYZ, MSB first, zero pad bits at the end.")
    w("# Records (bytes \"x:<hex>\", \"-\" empty; text values never contain spaces, '_' marks a space in")
    w("# manual-entry inputs):")
    w("#   label_ok      device_id code label: the canonical setup label for a 16-byte setup code")
    w("#   label_entry   input -> device_id code: manual-entry normalization (case-insensitive, I/L -> 1,")
    w("#                 O -> 0, '-' and spaces ignored in the code part; device ID hex in either case)")
    w("#   label_bad     input reason: must be refused (reason names the first failing rule)")
    w("#   invite_ok     fields, payload (79 bytes), qr text (DSP2I1:<127 chars>), device_id_hash expected in HELLO")
    w("#   invite_bad    input reason: must be refused; reason 'unsupported' = version not 1 (\"update the app\")")
    w("#   invite_time   created expires now expect: ok | expired (now > expires + 120) |")
    w("#                 clock_warning (created > now + 300, still usable) | invalid (span rules)")
    w("")

    # ---- labels
    labels = [
        ("zero", "000000000000", bytes(16)),
        ("ones", "ffffffffffff", b"\xff" * 16),
        ("seq", "a0b1c2d3e4f5", bytes(range(16))),
        ("rand", "89c9e69d72a7", bytes.fromhex("fd5b144a7bcff1dd4c00587c39bbd561")),
    ]
    for name, did, code in labels:
        w("label_ok name=%s device_id=%s code=%s label=%s" % (name, did, hx(code), label(did, code)))
    seq_code = bytes(range(16))
    canon = label_code(seq_code)
    # manual-entry variants of the "seq" label (code part normalized; device ID either case)
    def entry(inp, name):
        w("label_entry name=%s input=%s device_id=a0b1c2d3e4f5 code=%s" % (name, inp.replace(" ", "_"), hx(seq_code)))
    entry("DSP2:a0b1c2d3e4f5:" + canon, "canonical")
    entry("DSP2:A0B1C2D3E4F5:" + canon, "device_id_upper")
    entry("dsp2:a0b1c2d3e4f5:" + canon.lower(), "all_lower")
    groups = "-".join(canon[i:i + 4] for i in range(0, 28, 4))
    entry("DSP2:a0b1c2d3e4f5:" + groups, "hyphen_groups")
    entry("DSP2:a0b1c2d3e4f5:" + " ".join(canon[i:i + 7] for i in range(0, 28, 7)), "space_groups")
    # I/L/O look-alikes: replace the first '1' with 'L' / 'I' and the first '0' with 'O' if present
    if "1" in canon:
        entry("DSP2:a0b1c2d3e4f5:" + canon.replace("1", "L", 1), "l_for_1")
        entry("DSP2:a0b1c2d3e4f5:" + canon.replace("1", "i", 1), "i_for_1")
    if "0" in canon:
        entry("DSP2:a0b1c2d3e4f5:" + canon.replace("0", "O", 1), "o_for_0")
    good = "DSP2:a0b1c2d3e4f5:" + canon
    bad_check = canon[:26] + ("0" if canon[26] != "0" else "1") + canon[27]
    pad_set = canon[:25] + CROCKFORD[CROCKFORD.index(canon[25]) | 1] + canon[26:]
    bads = [
        ("empty", "", "prefix"),
        ("prefix", "DSP3:a0b1c2d3e4f5:" + canon, "prefix"),
        ("invite_prefix", "DSP2I1:" + canon, "prefix"),
        ("missing_field", "DSP2:" + canon, "fields"),
        ("extra_field", good + ":00", "fields"),
        ("device_id_short", "DSP2:a0b1c2d3e4:" + canon, "device_id"),
        ("device_id_nonhex", "DSP2:a0b1c2d3e4fg:" + canon, "device_id"),
        ("code_short", "DSP2:a0b1c2d3e4f5:" + canon[:27], "length"),
        ("code_long", "DSP2:a0b1c2d3e4f5:" + canon + "0", "length"),
        ("code_u", "DSP2:a0b1c2d3e4f5:" + canon[:5] + "U" + canon[6:], "charset"),
        ("code_symbol", "DSP2:a0b1c2d3e4f5:" + canon[:5] + "*" + canon[6:], "charset"),
        ("pad_bits", "DSP2:a0b1c2d3e4f5:" + pad_set, "pad"),
        ("check", "DSP2:a0b1c2d3e4f5:" + bad_check, "check"),
    ]
    if pad_set == canon:
        sys.exit("pad test vector degenerate")
    for name, inp, reason in bads:
        w("label_bad name=%s input=%s reason=%s" % (name, inp if inp else "-", reason))
    w("")

    # ---- invitations
    dev = bytes.fromhex("a0b1c2d3e4f5")
    pub = bytes(range(0x20, 0x40))
    token = bytes.fromhex("bacd0fa8879ea4dd104c412f93e1a7cb")
    created = 1795000000
    cases = [
        ("reference", 1, dev, pub, token, created + 600, created),
        ("zero_token", 1, dev, pub, bytes(16), created + 600, created),
        ("short_expiry", 1, bytes.fromhex("000000000001"), bytes(range(0x80, 0xa0)), b"\x5a" * 16, created + 1, created),
    ]
    for name, ver, d, p, t, exp, cr in cases:
        pl = invite_payload(ver, d, p, t, exp, cr)
        w("invite_ok name=%s version=%d device_id=%s device_static_pub=%s invite_token=%s expires_utc=%d "
          "created_utc=%d payload=%s qr=%s device_id_hash=%s"
          % (name, ver, hx(d), hx(p), hx(t), exp, cr, hx(pl), invite_text(pl), hx(id_hash(p))))
    ref = invite_payload(1, dev, pub, token, created + 600, created)
    txt = invite_text(ref)
    body = txt[len("DSP2I1:"):]

    def with_payload(pl):
        return invite_text(pl)

    def recheck(b63):
        return b63 + hashlib.sha256(b"DSP2 invite v1" + b63).digest()[:16]

    flipped = bytearray(ref)
    flipped[40] ^= 0x01  # token byte changed, check not updated
    last = CROCKFORD.index(body[-1])
    bad_invites = [
        ("prefix_label", "DSP2:" + body, "prefix"),
        ("prefix_version2_text", "DSP2I2:" + body, "prefix"),
        ("length_short", "DSP2I1:" + body[:-1], "length"),
        ("length_long", "DSP2I1:" + body + "0", "length"),
        ("lowercase", "DSP2I1:" + body.lower(), "charset"),
        ("letter_i", "DSP2I1:" + body[:10] + "I" + body[11:], "charset"),
        ("letter_o", "DSP2I1:" + body[:10] + "O" + body[11:], "charset"),
        ("hyphen", "DSP2I1:" + body[:10] + "-" + body[11:], "charset"),
        ("pad_bits", "DSP2I1:" + body[:-1] + CROCKFORD[last | 1], "pad"),
        ("check", with_payload(bytes(flipped)), "check"),
        ("unsupported_version", with_payload(recheck(bytes([2]) + ref[1:63])), "unsupported"),
        ("version_zero", with_payload(recheck(bytes([0]) + ref[1:63])), "unsupported"),
        ("zero_key", with_payload(recheck(ref[:7] + bytes(32) + ref[39:63])), "zero_key"),
        ("span_too_long", with_payload(recheck(ref[:55] + struct.pack("<I", created + 601) + ref[59:63])), "span"),
        ("expires_before_created", with_payload(recheck(ref[:55] + struct.pack("<I", created - 1) + ref[59:63])), "span"),
    ]
    if (last | 1) == last:
        sys.exit("pad test vector degenerate")
    for name, inp, reason in bad_invites:
        w("invite_bad name=%s input=%s reason=%s" % (name, inp, reason))
    times = [
        ("fresh", created, created + 600, created + 10, "ok"),
        ("at_expiry", created, created + 600, created + 600, "ok"),
        ("grace_end", created, created + 600, created + 720, "ok"),
        ("expired", created, created + 600, created + 721, "expired"),
        ("phone_clock_behind", created, created + 600, created - 300, "ok"),
        ("creator_clock_ahead", created, created + 600, created - 301, "clock_warning"),
        ("span_too_long", created, created + 601, created, "invalid"),
        ("zero_span", created, created, created, "ok"),
    ]
    for name, cr, exp, now, expect in times:
        w("invite_time name=%s created_utc=%d expires_utc=%d now_utc=%d expect=%s" % (name, cr, exp, now, expect))
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
