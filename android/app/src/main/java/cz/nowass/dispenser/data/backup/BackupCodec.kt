/**
 * Encoder and strict validating decoder of the versioned backup format (docs/BACKUP_FORMAT.md).
 *
 * Decoding never partially succeeds: it returns either complete, fully validated
 * [BackupContent] or the first [BackupError]. Unknown fields are rejected; a different
 * `schemaVersion` is reported as unsupported. Pure JVM code (no Android dependencies).
 */
object BackupCodec {
    const val FORMAT = "dispenser-backup"
    const val SCHEMA_VERSION = 1
    const val SIMULATION_ORIGIN = "SIMULATION"

    const val MAX_BYTES = 20 * 1024 * 1024
    const val MAX_SCHEDULES = 1_000
    const val MAX_HISTORY_EVENTS = 500_000
    const val MAX_PROCESSED = 100_000
    private const val MAX_TEXT = 1_000

    /** Ids generated by the app are UUIDs; this also keeps `@` (occurrence-id separator) out. */
    private val ID = Regex("[A-Za-z0-9._-]{1,64}")
    private val TIME: DateTimeFormatter = DateTimeFormatter.ofPattern("HH:mm")
    private val json = Json { prettyPrint = true }

    sealed interface Decoded {
        data class Valid(val content: BackupContent) : Decoded
        data class Invalid(val error: BackupError) : Decoded
    }

    // ------------------------------------------------------------------ encode

    fun encode(content: BackupContent): String = json.encodeToString(JsonElement.serializer(), toJson(content))

    private fun toJson(c: BackupContent): JsonObject = buildJsonObject {
        put("format", FORMAT)
        put("schemaVersion", SCHEMA_VERSION)
        put("exportedAt", c.exportedAt.toString())
        put("applicationVersion", c.applicationVersion)
        putJsonObject("settings") { put("displayName", c.displayName) }
        putJsonArray("schedules") { c.schedules.forEach { add(scheduleJson(it)) } }
        put("simulation", c.simulation?.let(::simulationJson) ?: JsonNull)
    }

    private fun scheduleJson(s: Schedule): JsonObject = buildJsonObject {
        put("id", s.id)
        put("revision", s.revision)
        put("name", s.name)
        put("enabled", s.enabled)
        put("amountMicrolitres", (Volume.mlToMicrolitres(s.amountMl) as Volume.Conversion.Ok).microlitres)
        put("startDate", s.startDate.toString())
        put("localTime", s.localTime.format(TIME))
        put("zoneId", s.zone.id)
        putJsonObject("recurrence") {
            when (val r = s.recurrence) {
                Recurrence.Once -> { put("kind", RecurrenceKind.ONCE.name); put("interval", 1); putJsonArray("weekdays") {} }
                is Recurrence.Daily -> { put("kind", RecurrenceKind.DAILY.name); put("interval", r.intervalDays); putJsonArray("weekdays") {} }
                is Recurrence.Weekly -> {
                    put("kind", RecurrenceKind.WEEKLY.name)
                    put("interval", r.intervalWeeks)
                    putJsonArray("weekdays") { r.weekdays.sorted().forEach { add(JsonPrimitive(it.name)) } }
                }
            }
        }
        put("endDate", s.endDate?.toString())
    }

    private fun simulationJson(sim: SimulationBackup): JsonObject = buildJsonObject {
        put("dataOrigin", SIMULATION_ORIGIN)
        put("state", sim.state?.let(::stateJson) ?: JsonNull)
        put("history", buildJsonArray { sim.history.sortedBy { it.seq }.forEach { add(eventJson(it)) } })
    }

    private fun stateJson(s: SimulationState): JsonObject = buildJsonObject {
        put("runId", s.runId)
        put("startedAt", s.startedAt.toString())
        put("clock", s.clock.toString())
        put("readiness", s.readiness.name)
        put("nextSeq", s.nextSeq)
        putJsonObject("reservoir") {
            put("capacityMicrolitres", s.reservoir.capacityUl)
            put("remainingMicrolitres", s.reservoir.remainingUl)
            put("updatedAt", s.reservoir.updatedAt.toString())
            put("blocked", s.reservoir.blocked)
            put("lowWarningLatched", s.reservoir.lowWarningLatched)
        }
        putJsonArray("processedOccurrences") {
            s.processedOccurrences.entries.sortedBy { it.key }.forEach { (id, date) ->
                add(buildJsonObject { put("occurrenceId", id); put("localDate", date.toString()) })
            }
        }
    }

    private fun eventJson(e: HistoryEvent): JsonObject = buildJsonObject {
        put("id", e.id)
        put("seq", e.seq)
        put("time", e.time.toString())
        put("type", e.type.name)
        put("origin", e.origin.name)
        put("reason", e.reason.name)
        put("scheduleId", e.scheduleId)
        put("scheduleNameSnapshot", e.scheduleNameSnapshot)
        put("occurrenceId", e.occurrenceId)
        put("requestedMicrolitres", e.requestedUl)
        put("dispensedMicrolitres", e.dispensedUl)
        put("reservoirBeforeMicrolitres", e.reservoirBeforeUl)
        put("reservoirAfterMicrolitres", e.reservoirAfterUl)
        put("capacityMicrolitres", e.capacityUl)
    }

    // ------------------------------------------------------------------ decode

    fun decode(bytes: ByteArray): Decoded {
        if (bytes.isEmpty()) return Decoded.Invalid(BackupError(BackupError.Kind.EMPTY))
        if (bytes.size > MAX_BYTES) return Decoded.Invalid(BackupError(BackupError.Kind.TOO_LARGE))
        val text = try {
            Charsets.UTF_8.newDecoder()
                .onMalformedInput(CodingErrorAction.REPORT)
                .onUnmappableCharacter(CodingErrorAction.REPORT)
                .decode(ByteBuffer.wrap(bytes)).toString()
        } catch (_: CharacterCodingException) {
            return Decoded.Invalid(BackupError(BackupError.Kind.NOT_JSON))
        }
        return decode(text.removePrefix("\uFEFF"))
    }

    fun decode(text: String): Decoded {
        if (text.isBlank()) return Decoded.Invalid(BackupError(BackupError.Kind.EMPTY))
        val root = try {
            Json.parseToJsonElement(text)
        } catch (_: SerializationException) {
            return Decoded.Invalid(BackupError(BackupError.Kind.NOT_JSON))
        } catch (_: IllegalArgumentException) {
            return Decoded.Invalid(BackupError(BackupError.Kind.NOT_JSON))
        }
        return try {
            Decoded.Valid(decodeRoot(root))
        } catch (f: Fail) {
            Decoded.Invalid(f.error)
        }
    }

    private class Fail(val error: BackupError) : Exception(null, null, false, false)

    private fun fail(kind: BackupError.Kind, path: String?, detail: String? = null): Nothing =
        throw Fail(BackupError(kind, path, detail))

    /** Strict field access on one JSON object, with the JSON path for error reports. */
    private class Obj(val o: JsonObject, val path: String) {
        fun p(k: String) = if (path.isEmpty()) k else "$path.$k"

        fun only(vararg keys: String): Obj {
            o.keys.firstOrNull { it !in keys }?.let { fail(BackupError.Kind.UNKNOWN_FIELD, p(it)) }
            return this
        }

        fun el(k: String): JsonElement = o[k] ?: fail(BackupError.Kind.MISSING_FIELD, p(k))
        fun isNull(k: String) = el(k) is JsonNull

        fun str(k: String): String {
            val e = el(k)
            if (e !is JsonPrimitive || e is JsonNull || !e.isString) fail(BackupError.Kind.WRONG_TYPE, p(k))
            return e.content
        }

        fun text(k: String): String = str(k).also { if (it.length > MAX_TEXT) fail(BackupError.Kind.INVALID_VALUE, p(k)) }
        fun textOrNull(k: String): String? = if (isNull(k)) null else text(k)

        fun long(k: String): Long {
            val e = el(k)
            if (e !is JsonPrimitive || e is JsonNull || e.isString) fail(BackupError.Kind.WRONG_TYPE, p(k))
            return e.longOrNull ?: fail(BackupError.Kind.WRONG_TYPE, p(k))
        }

        fun longOrNull(k: String): Long? = if (isNull(k)) null else long(k)

        fun int(k: String): Int {
            val v = long(k)
            if (v !in Int.MIN_VALUE..Int.MAX_VALUE) fail(BackupError.Kind.INVALID_VALUE, p(k))
            return v.toInt()
        }

        fun bool(k: String): Boolean {
            val e = el(k)
            if (e !is JsonPrimitive || e is JsonNull || e.isString) fail(BackupError.Kind.WRONG_TYPE, p(k))
            return e.booleanOrNull ?: fail(BackupError.Kind.WRONG_TYPE, p(k))
        }

        fun obj(k: String): Obj = (el(k) as? JsonObject)?.let { Obj(it, p(k)) } ?: fail(BackupError.Kind.WRONG_TYPE, p(k))
        fun objOrNull(k: String): Obj? = if (isNull(k)) null else obj(k)

        fun array(k: String, max: Int): JsonArray {
            val a = el(k) as? JsonArray ?: fail(BackupError.Kind.WRONG_TYPE, p(k))
            if (a.size > max) fail(BackupError.Kind.TOO_MANY_ITEMS, p(k))
            return a
        }

        fun objects(k: String, max: Int): List<Obj> = array(k, max).mapIndexed { i, e ->
            Obj(e as? JsonObject ?: fail(BackupError.Kind.WRONG_TYPE, "${p(k)}[$i]"), "${p(k)}[$i]")
        }

        inline fun <T> parsed(k: String, parse: (String) -> T): T {
            val raw = str(k)
            return try {
                parse(raw)
            } catch (_: DateTimeException) {
                fail(BackupError.Kind.INVALID_VALUE, p(k))
            } catch (_: IllegalArgumentException) {
                fail(BackupError.Kind.INVALID_VALUE, p(k))
            }
        }

        inline fun <T> parsedOrNull(k: String, parse: (String) -> T): T? = if (isNull(k)) null else parsed(k, parse)

        fun id(k: String): String = str(k).also { if (!ID.matches(it)) fail(BackupError.Kind.INVALID_VALUE, p(k)) }
    }

    private inline fun <reified E : Enum<E>> enumOf(raw: String): E =
        enumValues<E>().firstOrNull { it.name == raw } ?: throw IllegalArgumentException("unknown value")

    private fun zoneOf(raw: String): ZoneId {
        // IANA region ids only (no fixed offsets): schedules must follow DST rules.
        require(raw in ZoneId.getAvailableZoneIds()) { "unknown zone" }
        return ZoneId.of(raw)
    }

    private fun decodeRoot(root: JsonElement): BackupContent {
        val r = Obj(root as? JsonObject ?: fail(BackupError.Kind.NOT_A_BACKUP, null), "")
        val format = r.o["format"]
        if (format !is JsonPrimitive || !format.isString || format.content != FORMAT) fail(BackupError.Kind.NOT_A_BACKUP, "format")
        val version = r.o["schemaVersion"]
        if (version !is JsonPrimitive || version is JsonNull || version.isString || version.longOrNull == null) {
            fail(BackupError.Kind.UNSUPPORTED_VERSION, "schemaVersion")
        }
        if (version.longOrNull != SCHEMA_VERSION.toLong()) fail(BackupError.Kind.UNSUPPORTED_VERSION, "schemaVersion", version.content)

        r.only("format", "schemaVersion", "exportedAt", "applicationVersion", "settings", "schedules", "simulation")
        val exportedAt = r.parsed("exportedAt", Instant::parse)
        val appVersion = r.text("applicationVersion")

        val settings = r.obj("settings").only("displayName")
        val rawName = settings.textOrNull("displayName")
        if (DisplayNameRules.validate(rawName) != null) fail(BackupError.Kind.INVALID_VALUE, settings.p("displayName"))

        val schedules = r.objects("schedules", MAX_SCHEDULES).map(::decodeSchedule)
        val seen = HashSet<String>()
        schedules.forEachIndexed { i, s -> if (!seen.add(s.id)) fail(BackupError.Kind.DUPLICATE_ID, "schedules[$i].id") }

        return BackupContent(
            exportedAt = exportedAt,
            applicationVersion = appVersion,
            displayName = DisplayNameRules.normalize(rawName),
            schedules = schedules,
            simulation = r.objOrNull("simulation")?.let(::decodeSimulation),
        )
    }

    private fun decodeSchedule(s: Obj): Schedule {
        s.only("id", "revision", "name", "enabled", "amountMicrolitres", "startDate", "localTime", "zoneId", "recurrence", "endDate")
        val id = s.id("id")
        val revision = s.int("revision")
        if (revision < 1) fail(BackupError.Kind.INVALID_VALUE, s.p("revision"))
        val name = s.text("name")
        val enabled = s.bool("enabled")
        val amountUl = s.long("amountMicrolitres")
        if (!Volume.isValidMicrolitres(amountUl)) fail(BackupError.Kind.INVALID_VALUE, s.p("amountMicrolitres"))
        val startDate = s.parsed("startDate", LocalDate::parse)
        val localTime = s.parsed("localTime") { LocalTime.parse(it, TIME) }
        val zone = s.parsed("zoneId", ::zoneOf)
        val endDate = s.parsedOrNull("endDate", LocalDate::parse)

        val rec = s.obj("recurrence").only("kind", "interval", "weekdays")
        val kind = rec.parsed("kind") { enumOf<RecurrenceKind>(it) }
        val interval = rec.int("interval")
        val weekdayNames = rec.array("weekdays", 7).mapIndexed { i, e ->
            if (e !is JsonPrimitive || e is JsonNull || !e.isString) fail(BackupError.Kind.WRONG_TYPE, "${rec.p("weekdays")}[$i]")
            e.content
        }
        val weekdays = weekdayNames.mapIndexed { i, n ->
            DayOfWeek.entries.firstOrNull { it.name == n } ?: fail(BackupError.Kind.INVALID_VALUE, "${rec.p("weekdays")}[$i]")
        }
        if (weekdays.toSet().size != weekdays.size) fail(BackupError.Kind.INVALID_VALUE, rec.p("weekdays"))
        when (kind) {
            RecurrenceKind.ONCE -> {
                if (interval != 1) fail(BackupError.Kind.INVALID_VALUE, rec.p("interval"))
                if (weekdays.isNotEmpty()) fail(BackupError.Kind.INVALID_VALUE, rec.p("weekdays"))
                if (endDate != null) fail(BackupError.Kind.INVALID_VALUE, s.p("endDate"))
            }
            RecurrenceKind.DAILY -> if (weekdays.isNotEmpty()) fail(BackupError.Kind.INVALID_VALUE, rec.p("weekdays"))
            RecurrenceKind.WEEKLY -> Unit
        }

        val draft = ScheduleDraft(
            name = name,
            amountMl = Volume.microlitresToMl(amountUl),
            startDate = startDate,
            localTime = localTime,
            kind = kind,
            interval = interval,
            weekdays = weekdays.toSet(),
            endDate = endDate,
            enabled = enabled,
            zone = zone,
        )
        val errors = ScheduleValidator.validate(draft)
        if (errors.isNotEmpty()) fail(BackupError.Kind.INVALID_SCHEDULE, s.path, errors.sorted().joinToString { it.name })
        // Name kept exactly as exported (like the database mapper).
        return draft.toSchedule(id, revision).copy(name = name)
    }

    private fun decodeSimulation(sim: Obj): SimulationBackup {
        sim.only("dataOrigin", "state", "history")
        if (sim.str("dataOrigin") != SIMULATION_ORIGIN) fail(BackupError.Kind.INVALID_VALUE, sim.p("dataOrigin"))
        val state = sim.objOrNull("state")?.let(::decodeState)

        val history = sim.objects("history", MAX_HISTORY_EVENTS).map(::decodeEvent)
        val ids = HashSet<String>()
        val seqs = HashSet<Long>()
        history.forEachIndexed { i, e ->
            if (!ids.add(e.id)) fail(BackupError.Kind.DUPLICATE_ID, "simulation.history[$i].id")
            if (!seqs.add(e.seq)) fail(BackupError.Kind.INCONSISTENT_SIMULATION, "simulation.history[$i].seq")
            if (state != null && e.seq >= state.nextSeq) fail(BackupError.Kind.INCONSISTENT_SIMULATION, "simulation.history[$i].seq")
        }
        return SimulationBackup(state, history.sortedBy { it.seq })
    }

    private fun decodeState(s: Obj): SimulationState {
        s.only("runId", "startedAt", "clock", "readiness", "nextSeq", "reservoir", "processedOccurrences")
        val runId = s.id("runId")
        val startedAt = s.parsed("startedAt", Instant::parse)
        val clock = s.parsed("clock", Instant::parse)
        if (clock.isBefore(startedAt)) fail(BackupError.Kind.INCONSISTENT_SIMULATION, s.p("clock"))
        val readiness = s.parsed("readiness") { enumOf<DeviceReadiness>(it) }
        val nextSeq = s.long("nextSeq")
        if (nextSeq < 1) fail(BackupError.Kind.INVALID_VALUE, s.p("nextSeq"))

        val r = s.obj("reservoir").only("capacityMicrolitres", "remainingMicrolitres", "updatedAt", "blocked", "lowWarningLatched")
        val capacity = r.long("capacityMicrolitres")
        val remaining = r.long("remainingMicrolitres")
        val updatedAt = r.parsed("updatedAt", Instant::parse)
        val blocked = r.bool("blocked")
        val latched = r.bool("lowWarningLatched")
        val reservoir = try {
            ReservoirState(capacity, remaining, updatedAt, blocked, latched)
        } catch (_: IllegalArgumentException) {
            fail(BackupError.Kind.INVALID_VALUE, r.path)
        }

        val processed = LinkedHashMap<String, LocalDate>()
        s.objects("processedOccurrences", MAX_PROCESSED).forEach { p ->
            p.only("occurrenceId", "localDate")
            val occurrenceId = p.str("occurrenceId")
            val date = p.parsed("localDate", LocalDate::parse)
            val scheduleId = occurrenceId.substringBeforeLast('@', missingDelimiterValue = "")
            if (!ID.matches(scheduleId) || occurrenceId != "$scheduleId@$date") {
                fail(BackupError.Kind.INCONSISTENT_SIMULATION, p.p("occurrenceId"))
            }
            if (processed.put(occurrenceId, date) != null) fail(BackupError.Kind.DUPLICATE_ID, p.p("occurrenceId"))
        }

        return SimulationState(runId, startedAt, clock, reservoir, readiness, processed, nextSeq)
    }

    private fun decodeEvent(e: Obj): HistoryEvent {
        e.only(
            "id", "seq", "time", "type", "origin", "reason", "scheduleId", "scheduleNameSnapshot", "occurrenceId",
            "requestedMicrolitres", "dispensedMicrolitres", "reservoirBeforeMicrolitres", "reservoirAfterMicrolitres", "capacityMicrolitres",
        )
        val id = e.text("id")
        if (id.isBlank()) fail(BackupError.Kind.INVALID_VALUE, e.p("id"))
        val seq = e.long("seq")
        if (seq < 1) fail(BackupError.Kind.INVALID_VALUE, e.p("seq"))
        val origin = e.parsed("origin") { enumOf<EventOrigin>(it) }
        // Simulated data only: a backup can never introduce "real device" history.
        if (origin != EventOrigin.SIMULATION) fail(BackupError.Kind.INVALID_VALUE, e.p("origin"))
        val time = e.parsed("time", Instant::parse)
        val type = e.parsed("type") { enumOf<HistoryEventType>(it) }
        val reason = e.parsed("reason") { enumOf<EventReason>(it) }
        val scheduleId = e.textOrNull("scheduleId")
        val name = e.textOrNull("scheduleNameSnapshot")
        val occurrenceId = e.textOrNull("occurrenceId")
        val requested = e.longOrNull("requestedMicrolitres")
        val dispensed = e.long("dispensedMicrolitres")
        val before = e.long("reservoirBeforeMicrolitres")
        val after = e.long("reservoirAfterMicrolitres")
        val capacity = e.long("capacityMicrolitres")
        return try {
            HistoryEvent(id, seq, time, type, origin, reason, scheduleId, name, occurrenceId, requested, dispensed, before, after, capacity)
        } catch (_: IllegalArgumentException) {
            fail(BackupError.Kind.INVALID_VALUE, e.path)
        }
    }
}
